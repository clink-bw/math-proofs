def ind_cert(x, y, R, p, Sv, q, JMAX):
    refs = []
    for j in range(1, JMAX + 1):
        i = math.ceil((j * R - x) / p)
        p_ok = p * i + x < (j + 1) * R
        i2 = math.ceil((j * Sv - y) / q)
        q_ok = q * i2 + y < (j + 1) * Sv
        if p_ok and q_ok:
            return (j, tuple(refs), (i, i2))
        refs.append(("P", i - 1) if not p_ok else ("Q", i2 - 1))
    raise RuntimeError("no return within JMAX")


def ind_blocks(R, p, Sv, q, JMAX):
    vr = lambda e: e[0] + e[1] * R
    vs = lambda e: e[0] + e[1] * Sv
    apts = [(-p * i, j) for j in range(1, JMAX + 2) for i in range(-25, 26)]
    bpts = [(-q * i, j) for j in range(1, JMAX + 2) for i in range(-25, 26)]
    blocks = []
    for au, av in cells((0, 0), (0, 1), apts, vr):
        row = []
        for bu, bv in cells((0, 0), (0, 1), bpts, vs):
            cert = ind_cert((vr(au) + vr(av)) / 2, (vs(bu) + vs(bv)) / 2, R, p, Sv, q, JMAX)
            if row and row[-1][2] == cert:
                row[-1] = (row[-1][0], bv, cert)
            else:
                row.append((bu, bv, cert))
        if blocks and blocks[-1][2] == row:
            blocks[-1] = (blocks[-1][0], av, row)
        else:
            blocks.append((au, av, row))
    return blocks


