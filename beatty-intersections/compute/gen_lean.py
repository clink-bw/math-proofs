def icbrt(n):
    r = int(round(n ** (1.0 / 3)))
    while r ** 3 > n:
        r -= 1
    while (r + 1) ** 3 <= n:
        r += 1
    return r


# ----------------------------------------------------------------------------- text helpers

def lin(e, sym):
    """(p, q) -> Lean text for p + q*sym."""
    p, q = e
    if q == 0:
        return str(p)
    qs = sym if q == 1 else (f"-{sym}" if q == -1 else f"{q} * {sym}")
    if p == 0:
        return qs
    return f"{qs} + {p}" if p > 0 else f"{qs} - {-p}"


def off(name, i):
    return name if i == 0 else (f"{name} + {i}" if i > 0 else f"{name} - {-i}")


def tac(i):
    """Closing tactic: an integer offset introduces a cast that must be pushed first."""
    return "by linarith" if i == 0 else "by push_cast; linarith"


def nav(idx, n):
    return "; ".join(["right"] * idx + (["left"] if idx < n - 1 else []))


def leaf(cert, gaps, indent):
    g, refs, (i, i2) = cert
    parts = []
    for kind, i0 in refs:
        var, proj = ("k", "h.1") if kind == "P" else ("l", "h.2")
        parts.append(f"fun h => not_hit (by norm_num) ({off(var, i0)}) ({tac(i0)}) ({tac(i0)}) {proj}")
    hit = f"⟨⟨{off('k', i)}, {tac(i)}, {tac(i)}⟩, ⟨{off('l', i2)}, {tac(i2)}, {tac(i2)}⟩⟩"
    body = hit if not parts else "⟨" + f",\n{indent}    ".join(parts + [hit]) + "⟩"
    return f"{nav(gaps.index(g), len(gaps))}\n{indent}  exact {body}"


def cells(lo, hi, pts, val):
    inside = {e for e in pts if val(lo) + 1e-9 < val(e) < val(hi) - 1e-9}
    allp = sorted({lo, hi} | inside, key=val)
    return list(zip(allp, allp[1:]))


def alternatives(gaps, neg, pos):
    out = []
    for g in gaps:
        terms = [neg(j) for j in range(1, g)] + [pos(g)]
        out.append("    (" + " ∧ ".join(terms) + ")")
    return " ∨\n".join(out)


