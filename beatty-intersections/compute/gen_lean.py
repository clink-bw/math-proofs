#!/usr/bin/env python3
"""Generate the Lean proofs of the gap sets of four intersections of Beatty sequences.

    python3 beatty-intersections/compute/gen_lean.py        (writes lean/BeattyGaps/*.lean)

Idea.  If alpha * s' = d with d a positive integer, then (multiplying by s')
    m in B(alpha)  <=>  some multiple of d lies in [m s', m s' + s').
So membership of m + j is a statement about the real number t = m s', and "which j >= 1 is the
first with m + j in both sequences" depends only on where two offsets a, b lie:
    a = d k - t   (k the witness for the first sequence),   b likewise for the second.

* Dependent pairs (sqrt D with 1 + sqrt 3 or the golden ratio): b = a + c for an integer c with
  finitely many possible values, so the analysis is one-dimensional in a.
* Independent pairs (sqrt 2 with sqrt 3; 2^(1/3) with 2^(2/3)): a and b are unrelated, and the
  analysis is over a grid of rectangles.

On each cell this script records a certificate: the gap g, witnesses for m + g, and for each
j < g which sequence misses m + j and between which two consecutive terms.  Lean then checks every
certificate by linear arithmetic.  Floating point is used only to choose the certificates.
"""
