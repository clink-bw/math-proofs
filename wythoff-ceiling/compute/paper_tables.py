#!/usr/bin/env python3
"""Print the case tables of the paper (Tables 2 and 3) from the certificates in gen_lean.py.

    python3 wythoff-ceiling/compute/paper_tables.py > wythoff-ceiling/paper/tables.tex

For each cell of positions t = t(m) and each j up to the gap, the entry says why m + j is or is
not a member, using the same lemma that the Lean proof uses for that case.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_lean as G  # noqa: E402

D_CODE = {"Dt_of_4": r"$\mathbf{4}$", "Dt_of_6": r"$\mathbf{6}$", "Dt_of_8": r"$\mathbf{8}$",
          "not_Dt_above": "a", "not_Dt_gap46": "b", "not_Dt_gap68": "c"}
N_CODE = {"Nt_of_1": r"$\ast$", "Nt_of_2": r"$\ast$", "Nt_of_3": r"$\ast$",
          "not_Nt_c1": "1", "not_Nt_c2": "2", "not_Nt_c3": "3", "not_Nt_c5": "5",
          "not_Nt_c7": "7"}

# The cells used in the proof of the gap sets (the dispatch in twice_next / missing_next).
D_ROWS = [("twice_D1a", r"$(\varphi^{-3}+\varphi^{-5},\ \varphi^{-2})$"),
          ("twice_D1b", r"$(\varphi^{-3}+\varphi^{-6},\ \varphi^{-3}+\varphi^{-5})$"),
          ("twice_D1c", r"$(\varphi^{-3},\ \varphi^{-3}+\varphi^{-6}]$"),
          ("twice_D2", r"$(\varphi^{-5},\ \varphi^{-4})$"),
          ("twice_D3", r"$(0,\ \varphi^{-6})$")]
N_ROWS = [("missing_N0", r"$\{\varphi^{-1}\}$"),
          ("missing_N1a", r"$[\varphi^{-3},\ 2\varphi^{-4})$"),
          ("missing_N1b", r"$(2\varphi^{-4},\ \varphi^{-2})$"),
          ("missing_N2", r"$[\varphi^{-5},\ \varphi^{-4})$"),
          ("missing_N3", r"$(0,\ \varphi^{-6})$")]


def row(kind, name, label, code):
    spec = next(c for c in G.CELLS if c[0] == name)
    _, _, cell, sp, _, _ = spec
    lemmas = G.SETS[kind]["lemmas"]
    if sp[0] == "next":
        g, branch = sp[1], None
    else:
        _, branch, g = sp
    entries = []
    for j in range(1, 14):
        if j > g:
            entries.append("")
        elif j == branch:
            entries.append("?")
        else:
            _, lem, _ = G.certificate(lemmas, cell, j, j == g)
            entries.append(code[lem])
    gap = f"{branch} or {g}" if branch else str(g)
    return f"{label} & {gap} & " + " & ".join(entries) + r" \\"


def table(kind, rows, code, caption, label, first):
    out = [r"\begin{table}[ht]", r"\centering", r"\small", r"\setlength{\tabcolsep}{3.2pt}",
           r"\begin{tabular}{llccccccccccccc}", r"\toprule",
           f"{first} & gap & " + " & ".join(f"${j}$" for j in range(1, 14)) + r" \\",
           r"\midrule"]
    out += [row(kind, n, lab, code) for n, lab in rows]
    out += [r"\bottomrule", r"\end{tabular}", f"\\caption{{{caption}}}", f"\\label{{{label}}}",
            r"\end{table}"]
    return "\n".join(out)


def main():
    print("% Generated by wythoff-ceiling/compute/paper_tables.py; do not edit.")
    print(table("D", D_ROWS, D_CODE,
                r"Why $m+j\in\mathcal D$ or $m+j\notin\mathcal D$, for $m$ with $t(m)$ in the "
                r"given cell. A bold $k$: $t(m+j)\in I_k$, so $m+j$ is in columns $1$ and $k$. "
                r"a: $t(m+j)\ge\varphi^{-2}$. b: $t(m+j)\in[\varphi^{-4},\varphi^{-3}]$. "
                r"c: $t(m+j)\in[\varphi^{-6},\varphi^{-5}]$. In cases a, b, c no even column "
                r"$\ge4$ contains $m+j$. ?: either, see the text.",
                "tab:twice", r"cell of $t(m)$"))
    print()
    print(table("N", N_ROWS, N_CODE,
                r"Why $m+j\in\mathcal M$ or $m+j\notin\mathcal M$, for $m$ with $\varphi-t(m)$ "
                r"in the given cell. A number $k$: $m+j$ is in column $k$. "
                r"$\ast$: $m+j\in\mathcal M$. ?: either, see the text.",
                "tab:missing", r"cell of $\varphi-t(m)$"))


if __name__ == "__main__":
    main()
